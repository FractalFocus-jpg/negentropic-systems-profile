<#
UOS_HEARTBEAT_SYNC.ps1
- Pulls latest coherence samples from the live dashboard (snapshot.json)
- Computes simple metrics (samples, mean/min/max/std)
- Reads agent status.json files from the Obsidian vault
- Writes a unified “pulse block” into OS/AC3_LIVE_DASHBOARD.md between markers

Designed to be run by Scheduled Task (every 5 minutes).
#>

param(
  [string]$VaultRoot = 'C:\Users\alexl\the living tapestry',
  [string]$RepoRoot  = 'C:\Users\alexl\Desktop\tapestry-codex-starter',
  [string]$SnapshotUrl = 'http://localhost:5055/snapshot.json'
)

$ErrorActionPreference = 'Stop'

function Get-StdDev([double[]]$xs) {
  if (-not $xs -or $xs.Count -lt 2) { return 0.0 }
  $avg = ($xs | Measure-Object -Average).Average
  $var = ($xs | ForEach-Object { [math]::Pow(($_ - $avg), 2) } | Measure-Object -Sum).Sum / $xs.Count
  return [math]::Sqrt($var)
}

$ts = Get-Date
$iso = $ts.ToString('yyyy-MM-ddTHH:mm:ss.ffffzzz')

# --- Dashboard samples ---
$dashStatus = 'OFFLINE'
$samples = 0
$mean = $null
$min = $null
$max = $null
$std = $null

try {
  $resp = Invoke-WebRequest -Uri $SnapshotUrl -UseBasicParsing -TimeoutSec 3
  $data = $resp.Content | ConvertFrom-Json
  # self_observing_dashboard.py returns a JSON array: [{t,c}, ...]
  if ($data -is [System.Array] -and $data.Count -gt 0) {
    $vals = @($data | ForEach-Object { [double]$_.c })
    $samples = $vals.Count
    $mean = [math]::Round(($vals | Measure-Object -Average).Average, 4)
    $min  = [math]::Round(($vals | Measure-Object -Minimum).Minimum, 4)
    $max  = [math]::Round(($vals | Measure-Object -Maximum).Maximum, 4)
    $std  = [math]::Round((Get-StdDev $vals), 4)
    $dashStatus = 'ONLINE'
  } else {
    $dashStatus = 'ONLINE (buffer empty — click Start in UI)'
  }
} catch {
  $dashStatus = 'OFFLINE'
}

# --- Agent status from vault ---
$agentsPath = Join-Path $VaultRoot 'OS\agents'
$agentRows = @()
if (Test-Path -LiteralPath $agentsPath) {
  Get-ChildItem -LiteralPath $agentsPath -Directory -ErrorAction SilentlyContinue | ForEach-Object {
    $name = $_.Name
    $sf = Join-Path $_.FullName 'status.json'
    $st = 'unknown'
    $hb = ''
    if (Test-Path -LiteralPath $sf) {
      try {
        $j = (Get-Content -LiteralPath $sf -Raw | ConvertFrom-Json)
        $st = $j.status
        $hb = $j.timestamp
      } catch { }
    }
    $agentRows += [PSCustomObject]@{Name=$name; Status=$st; Heartbeat=$hb}
  }
}
$agentRows = $agentRows | Sort-Object Name

# --- Build pulse block ---
$pulse = New-Object System.Collections.Generic.List[string]
$pulse.Add('<!-- UOS_PULSE_BLOCK:START -->')
$pulse.Add('# AC3 LIVE DASHBOARD')
$pulse.Add("*Last Updated: $iso*")
$pulse.Add('')
$pulse.Add('## Unified Live Links')
$pulse.Add('- Web UI (real-time): http://localhost:5055')
$pulse.Add('- JSON feed (for sync/audit): http://localhost:5055/snapshot.json')
$pulse.Add('')
$pulse.Add('## Coherence Snapshot (from dashboard)')
$pulse.Add("- Status: **$dashStatus**")
$pulse.Add(("- Samples: **{0}**" -f $samples))
if ($mean -ne $null) {
  $pulse.Add(("- Mean: **{0}** | Min: **{1}** | Max: **{2}** | Std: **{3}**" -f $mean,$min,$max,$std))
}
$pulse.Add('')
$pulse.Add('## Agent Mesh Status (from vault)')
$pulse.Add('| Agent | Status | Last Heartbeat |')
$pulse.Add('|---|---|---|')
foreach ($r in $agentRows) {
  $pulse.Add("| $($r.Name) | $($r.Status) | $($r.Heartbeat) |")
}
$pulse.Add('')
$pulse.Add('## Notes')
$pulse.Add('- This page is auto-regenerated by `UOS_HEARTBEAT_SYNC.ps1` for auditability.')
$pulse.Add('- For Drive->Vault live objectives, use the Drive Inbox sync (separate script).')
$pulse.Add('<!-- UOS_PULSE_BLOCK:END -->')

$outPath = Join-Path $VaultRoot 'OS\AC3_LIVE_DASHBOARD.md'

# If file exists, replace block; else create
if (Test-Path -LiteralPath $outPath) {
  $raw = Get-Content -LiteralPath $outPath -Raw
  if ($raw -match '<!-- UOS_PULSE_BLOCK:START -->' -and $raw -match '<!-- UOS_PULSE_BLOCK:END -->') {
    $new = [regex]::Replace($raw, '(?s)<!-- UOS_PULSE_BLOCK:START -->.*?<!-- UOS_PULSE_BLOCK:END -->', ($pulse -join "`r`n"))
    $new | Out-File -LiteralPath $outPath -Encoding UTF8
  } else {
    # append pulse block at top
    (($pulse -join "`r`n") + "`r`n`r`n" + $raw) | Out-File -LiteralPath $outPath -Encoding UTF8
  }
} else {
  $pulse | Out-File -LiteralPath $outPath -Encoding UTF8
}
